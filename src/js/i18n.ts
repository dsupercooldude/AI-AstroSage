let currentLanguage: SupportedLanguage = 'en';

// Load stored language preference if exists
try {
  const saved = localStorage.getItem('gl_language') as SupportedLanguage;
  if (saved && TRANSLATIONS[saved]) {
    currentLanguage = saved;
  }
} catch (e) {}

export function getLanguage(): SupportedLanguage {
  return currentLanguage;
}

export function setLanguage(lang: SupportedLanguage): void {
  if (TRANSLATIONS[lang]) {
    currentLanguage = lang;
    try {
      localStorage.setItem('gl_language', lang);
    } catch (e) {}
    if (typeof window !== 'undefined') {
      window.dispatchEvent(new CustomEvent('languageChanged', { detail: lang }));
    }
  }
}

export function t(key: string, lang?: string, fallback?: string): string {
  const l = (lang as SupportedLanguage) || currentLanguage || 'en';
  const dict = TRANSLATIONS[l] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || fallback || key;
}

// Attach globally for JSX scripts
if (typeof window !== 'undefined') {
  (window as any).TRANSLATIONS = TRANSLATIONS;
  (window as any).SUPPORTED_LANGUAGES = SUPPORTED_LANGUAGES;
  (window as any).t = t;
  (window as any).__t = t;
  (window as any).getLanguage = getLanguage;
  (window as any).setLanguage = setLanguage;
}
